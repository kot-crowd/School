# Определяем функцию greet_user, которая будет запрашивать имя и возраст,
# а затем выводить приветственное сообщение или отказ в доступе.
def greet_user():
    # Запрашиваем у пользователя имя.
    name = input("Введите ваше имя: ")
    
    # Цикл для корректного ввода возраста (целое положительное число).
    while True:
        try:
            # Запрашиваем возраст и пытаемся преобразовать в целое число.
            age = int(input("Введите ваш возраст: "))
            # Проверяем, что возраст положительный.
            if age > 0:
                break  # Ввод корректен — выходим из цикла.
            else:
                print("Возраст должен быть положительным числом. Попробуйте снова.")
        except ValueError:
            # Если преобразование в int не удалось, выводим сообщение об ошибке.
            print("Ошибка: необходимо ввести целое число. Попробуйте снова.")
    
    # Проверяем, достиг ли пользователь 18 лет.
    if age < 18:
        print("Доступ запрещён. Вам должно быть 18 лет или больше.")
        return  # Завершаем выполнение функции
    
    # Определяем функцию для выбора правильного склонения слова "год".
    def get_year_word(years):
        """
        Возвращает правильную форму слова "год" в зависимости от числа.
        Для 1, 21, 31, ... -> "год"
        Для 2-4, 22-24, 32-34, ... -> "года"
        Для остальных -> "лет"
        """
        last_digit = years % 10
        last_two = years % 100
        
        if 11 <= last_two <= 14:
            return "лет"
        elif last_digit == 1:
            return "год"
        elif 2 <= last_digit <= 4:
            return "года"
        else:
            return "лет"
    
    # Получаем правильное слово для возраста.
    year_word = get_year_word(age)
    
    # Формируем и выводим приветственное сообщение.
    message = f"Привет, {name}! Тебе {age} {year_word}"
    print(message)

# Проверяем, запущен ли скрипт напрямую.
if __name__ == "__main__":
    greet_user()